def rows_of(ch):
    rows = GLYPHS[ch]
    assert len(rows) == 7 and all(len(r) == 5 and set(r) <= set(".#") for r in rows), ch
    return [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]


def generate():
    chars = [chr(c) for c in range(0x20, 0x7F)]
    missing = [c for c in chars if c not in GLYPHS]
    assert not missing, f"missing glyphs: {missing}"
    lines = ["/* Generated by gen_font.py: a 5 x 7 font for ASCII 0x20..0x7E, one byte",
             "   per row, bit 4 = leftmost column.  Edit gen_font.py, not this file. */",
             "#ifndef FONT5X7_H", "#define FONT5X7_H", "",
             "#define FONT_FIRST 0x20", "#define FONT_LAST 0x7e", "#define FONT_W 5", "#define FONT_H 7", "",
             "static const unsigned char font5x7[FONT_LAST - FONT_FIRST + 1][FONT_H] = {"]
    for ch in chars:
        label = {"\\": "backslash", "'": "quote", '"': "dquote"}.get(ch, ch)
        lines.append("    {" + ", ".join(f"0x{v:02x}" for v in rows_of(ch)) + "},  /* " + label + " */")
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    out = Path(__file__).with_name("font5x7.h")
    out.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
