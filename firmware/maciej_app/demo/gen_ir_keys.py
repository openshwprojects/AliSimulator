#!/usr/bin/env python3
"""Generate ir_keys.h: the button names of the Opticum HD N2's remote, from
the original application's own key table (dumps/dump_maciej.bin).

The application maps a received NEC code to a key by its 16-bit table code,
((code >> 16) & 0xFF) << 8 | (code & 0xFF) of the 32 bits as its decoder
shifts them in (src/ir_remote.py: "nec" coding).  Its virtual key numbers are
the SDK's shifted by two from POWER on (Libcore 8.x; ir_remote.VKEY_FALLBACKS
lists the shifted values first).  Codes that two keys share get both names.

    python firmware/maciej_app/demo/gen_ir_keys.py
"""
from pathlib import Path
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tools"))

import ir_remote          # noqa: E402
import maciej_image       # noqa: E402


def vkey_names():
    names = {14: "OK", 16: "EXIT"}           # the remote's labels (ir_remote's aliases ENTER / BACK)
    for name, value in ir_remote.VKEYS.items():
        if value <= 16:
            names.setdefault(value, name)
    for name, values in ir_remote.VKEY_FALLBACKS.items():
        names.setdefault(values[0], name)
    return names


def key_table():
    app = maciej_image.extract_application((ROOT / "dumps" / "dump_maciej.bin").read_bytes())
    ram = np.zeros(0x2000000, dtype=np.uint8)
    ram[0x200:0x200 + len(app)] = np.frombuffer(app, dtype=np.uint8)   # loaded at 0x80000200
    return ir_remote.find_key_table(ram)


def generate():
    names = vkey_names()
    by_code = {}
    for vkey, code in sorted(key_table().items()):
        label = names.get(vkey, f"KEY{vkey}")
        by_code.setdefault(code, [])
        if label not in by_code[code]:
            by_code[code].append(label)
    entries = sorted(key_table().items())              # (vkey, code), as the original's table
    lines = ["/* Generated by gen_ir_keys.py from dump_maciej.bin's own key table: the",
             "   16-bit code ((code >> 16) & 0xFF) << 8 | (code & 0xFF) of a received NEC",
             "   frame and the name of its button.  The codes are kept in the SDK's",
             "   struct ir_key_map_t layout (key_info = 0x0011 | code << 16: a pressed",
             "   remote key; then the virtual key), as the original application has its",
             "   table -- which is how the emulator's virtual remote (ir_remote.",
             "   find_key_table, tv_gui.py) finds the codes in this demo too.",
             "   Edit gen_ir_keys.py, not this file. */",
             "#ifndef IR_KEYS_H", "#define IR_KEYS_H", "",
             "struct ir_key_map { unsigned int key_info, vkey; };", "",
             f"#define IR_KEY_COUNT {len(entries)}",
             "static const struct ir_key_map ir_key_map[IR_KEY_COUNT] = {"]
    for vkey, code in entries:
        lines.append(f"    {{0x{code:04x}0011u, {vkey}}},")
    lines += ["};", "", "/* the button(s) of each entry's code */",
              "static const char *const ir_key_names[IR_KEY_COUNT] = {"]
    for _vkey, code in entries:
        lines.append(f'    "{"/".join(by_code[code])}",')
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    out = Path(__file__).with_name("ir_keys.h")
    out.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
